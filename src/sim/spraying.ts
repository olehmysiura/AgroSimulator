// ============================================================================
// Умови внесення ЗЗР і добрив: норма витрати, погода в момент обробки
// (вітер, дощ, прогноз, спека, холод, сніг/мерзлий ґрунт), фаза культури,
// строк очікування, кратність обробок, ЕПШ. Повертає фактичну ефективність
// і формує розбір помилок.
// ============================================================================
import { CROPS, PESTICIDES, PEST_EPSH, SPRAYS, gddForBbch } from './data';
import { liveCrop } from './diagnostics';
import { addLog, addMistake } from './engine';
import { layer } from './soil';
import type { ClimateMode, Crop, SimState, SprayOp, Weather } from './types';
import { generateWeather } from './weather';
import { clamp, fmt, round } from './util';

/** Прогноз погоди на наступну добу (той самий генератор, що й симуляція). */
export function forecast(s: SimState): Weather {
  let mode: ClimateMode = s.climate;
  if (mode === 'storm' || mode === 'frost' || s.climateUntil < s.day + 1) mode = 'normal';
  return generateWeather(s.zone, s.day + 1, mode);
}

/** Температура повітря під час роботи обприскувача. */
export function workTemp(s: SimState): number {
  const w = s.weather;
  return s.sprayMode === 'evening' ? round(Math.min(w.tAir, w.tMax - 6), 1) : w.tMax;
}

/** Орієнтовна кількість діб до збирання (за залишком суми температур). */
export function daysToHarvest(s: SimState, c: Crop): number {
  const def = CROPS[c.id];
  const rem = Math.max(0, gddForBbch(c.id, def.maturityBbch) - c.gdd);
  if (c.desiccated) return Math.ceil(rem / 40);
  const daily = Math.max(4, s.weather.tAir - def.baseTemp);
  return Math.round(rem / daily) + (c.bbch >= def.maturityBbch - 4 ? 3 : 7);
}

/** Вплив норми на ефективність пестициду (дозозалежна крива). */
export function doseEfficacy(op: SprayOp, dose: number): number {
  const d = SPRAYS[op];
  const [lo, hi] = d.rate;
  if (dose <= 0) return 0;
  if (dose < lo) return clamp(0.85 * (dose / lo) ** 1.6, 0.05, 0.85);
  if (dose <= d.def) return 0.85 + (0.15 * (dose - lo)) / Math.max(1e-6, d.def - lo);
  return Math.min(1.08, 1 + (0.06 * (dose - d.def)) / Math.max(1e-6, hi - d.def));
}

export interface AppResult { eff: number; notes: string[] }

/**
 * Перевіряє умови обробки, реєструє помилки й повертає фактичну ефективність.
 * Для пестицидів eff враховує і дозу; для добрив — частку, що дійшла до рослин.
 */
export function applicationConditions(s: SimState, op: SprayOp, dose: number): AppResult {
  const def = SPRAYS[op];
  const c = liveCrop(s);
  const w = s.weather;
  const fc = forecast(s);
  const pest = PESTICIDES.includes(op);
  const foliar = !def.spreader && def.mode !== 'soil' && op !== 'nitrogen';
  const tW = workTemp(s);
  const wind = s.sprayMode === 'evening' ? Math.min(w.wind, 2.1) : w.wind;
  const notes: string[] = [];
  let eff = pest ? doseEfficacy(op, dose) : 1;
  const unit = def.unit;

  // ---------------------------------------------------------------- норма витрати
  const [lo, hi] = def.rate;
  if (dose < lo * 0.95) {
    notes.push(`занижена норма ${fmt(dose, 2)} ${unit}`);
    if (pest) {
      addMistake(
        s,
        `Занижена норма: ${def.name} ${fmt(dose, 2)} ${unit} (зареєстровано ${fmt(lo, 2)}–${fmt(hi, 2)})`,
        'Нижня межа норми визначена так, щоб на листку/у ґрунті утворилась летальна для цільового об\'єкта доза. Сублетальна доза лише ослаблює бур\'яни, патогени чи шкідників; вижилі особини — найстійкіші, і саме вони дають наступне покоління. Так формується резистентність до цього механізму дії' + (def.moa ? ` (${def.moa}).` : '.'),
        `Ефективність лише ~${Math.round(eff * 100)}%, зростає ризик резистентності; повторна обробка неминуча.`,
      );
    } else if (op === 'liming' || op === 'pk') {
      addLog(s, 'warn', 'Норма нижче рекомендованої', `${fmt(dose, 1)} ${unit} — ефект меліорації/удобрення буде частковим.`);
    }
  }
  if (dose > hi * 1.05) {
    notes.push(`перевищена норма ${fmt(dose, 2)} ${unit}`);
    const over = dose / hi - 1;
    if (pest) {
      const loss = clamp(over * (def.group === 'herb' ? 0.35 : op === 'retardant' ? 0.25 : 0.12), 0.02, 0.3);
      addMistake(
        s,
        `Перевищено максимальну норму: ${def.name} ${fmt(dose, 2)} ${unit} (макс. ${fmt(hi, 2)})`,
        'Верхня межа норми — це доза, яку культура ще здатна знешкодити (детоксикувати) без пошкоджень. Надлишок д.р. накопичується в тканинах, порушує обмін речовин культури, довше зберігається в ґрунті (післядія на наступну культуру) та в продукції. Ефективність майже не зростає.',
        c && c.emerged ? `Фітотоксичність: опіки, затримка росту — втрата ~${Math.round(loss * 100)}% урожаю; підвищені залишки д.р.` : 'Підвищені залишки в ґрунті — ризик для наступної культури в сівозміні.',
      );
      if (c && c.emerged && op !== 'glyphosate' && op !== 'desiccant') {
        c.losses.phyto = (c.losses.phyto ?? 1) * (1 - loss);
        c.health = Math.max(10, c.health - loss * 60);
      }
    } else if (op === 'micro') {
      addMistake(
        s,
        `Надлишкова норма мікродобрива ${fmt(dose, 1)} ${unit}`,
        'Межа між достатнім і токсичним вмістом бору та цинку в рослині дуже вузька. Висока концентрація розчину на листку спричиняє крайовий опік, а надлишок бору токсичний для меристем.',
        'Опіки країв листя, пригнічення росту — втрата ~4% урожаю.',
      );
      if (c && c.emerged) c.losses.phyto = (c.losses.phyto ?? 1) * 0.96;
    }
  }

  // ---------------------------------------------------------------- зима / сніг / мерзлий ґрунт
  const frozen = s.snow > 3 || layer(s, 'surface').temp < -0.5 || w.tMax < 2;
  if (frozen) {
    notes.push(s.snow > 3 ? 'по снігу' : 'мерзлий ґрунт');
    if (def.mode === 'fert' && op !== 'micro' && op !== 'antistress') {
      const lost = op === 'nitrogen' ? 0.6 : 0.3;
      eff *= 1 - lost;
      addMistake(
        s,
        `Внесення ${op === 'nitrogen' ? 'азоту' : op === 'liming' ? 'меліоранту' : 'добрив'} по ${s.snow > 3 ? 'снігу' : 'мерзлому ґрунту'}`,
        'Мерзлий ґрунт не вбирає воду. Під час відлиги та сніготанення розчинені добрива стікають поверхнею у балки й водойми разом із талою водою. Внесення азоту на сніг чи мерзлий ґрунт заборонене правилами захисту вод від нітратного забруднення.',
        `Втрачено ~${Math.round(lost * 100)}% внесеного${op === 'nitrogen' ? ' азоту' : ''}; забруднення водойм, розподіл по полю нерівномірний.`,
      );
    } else if (pest || op === 'micro' || op === 'antistress') {
      eff *= 0.05;
      addMistake(
        s,
        `Обробка «${def.name}» у період зимового спокою`,
        'За температури біля або нижче 0 °C рослини не ростуть і майже не поглинають речовини через листок, продихи закриті; бур\'яни, патогени й шкідники неактивні. Краплі робочого розчину замерзають на поверхні, д.р. не транспортується до місця дії.' + (def.mode === 'soil' ? ' Ґрунтовий гербіцид не проникає в мерзлий ґрунт і змивається талою водою.' : ''),
        'Обробка практично не діє; препарат витрачено, д.р. потрапляє в стік талих вод.',
      );
    }
  }

  // ---------------------------------------------------------------- дощ зараз і за прогнозом
  const raining = w.rain >= 1 && !w.snowfall && !frozen;
  if (raining) {
    notes.push(`дощ ${fmt(w.rain, 1)} мм`);
    if (foliar) {
      const k = def.mode === 'contact' ? 0.25 : def.rainfast <= 2 ? 0.55 : 0.4;
      eff *= k;
      addMistake(
        s,
        `Обприскування під час дощу (${fmt(w.rain, 1)} мм): ${def.name}`,
        `Краплі дощу змивають робочий розчин з листка раніше, ніж д.р. встигає проникнути крізь кутикулу (${def.mode === 'contact' ? 'контактному препарату потрібна суха плівка на поверхні' : `системному потрібно щонайменше ${def.rainfast} год без опадів`}). Розчин розбавляється, стікає в ґрунт і на сусідні ділянки.`,
        `Фактична ефективність ~${Math.round(eff * 100)}%; частина препарату потрапляє в ґрунт і стічні води.`,
      );
    } else if (def.mode === 'soil' && w.rain > 20) {
      eff *= 0.7;
      addLog(s, 'warn', 'Злива після ґрунтового гербіциду', `${fmt(w.rain, 0)} мм: д.р. вимивається глибше за 3 см — екран слабший, ризик пошкодження насіння культури.`);
    } else if (op === 'nitrogen' && w.rain > 15) {
      addLog(s, 'warn', 'Азот під зливу', 'Сильний дощ переносить нітрати вглиб профілю; частина може вимитися за межі кореневої зони.');
    }
  } else if (foliar && def.rainfast >= 3 && fc.rain >= 5 && !fc.snowfall && s.sprayMode === 'evening') {
    eff *= 0.75;
    notes.push(`дощ уночі (${fmt(fc.rain, 0)} мм)`);
    addLog(s, 'warn', 'Дощ протягом дощостійкості', `Прогноз: ${fmt(fc.rain, 0)} мм уночі; препарату потрібно ${def.rainfast} год без опадів — частину буде змито.`);
  } else if (def.mode === 'soil' && fc.rain >= 5 && fc.rain <= 25) {
    addLog(s, 'info', 'Опади активують ґрунтовий гербіцид', `Прогноз на завтра ${fmt(fc.rain, 0)} мм — екран сформується швидше.`);
  }

  // ---------------------------------------------------------------- вітер (знесення)
  if (!def.spreader && op !== 'nitrogen' && wind > 5) {
    eff *= 0.35;
    notes.push(`вітер ${fmt(wind, 1)} м/с`);
    addMistake(
      s,
      `Обприскування (${def.name}) при вітрі ${fmt(wind)} м/с`,
      'За швидкості вітру понад 4–5 м/с дрібні краплі (<150 мкм) зі стандартних щілинних розпилювачів горизонтально зносяться повітряним потоком і випаровуються до осідання на листя. Утворюється «хмара» препарату, що дрейфує на сотні метрів.',
      '≈65% препарату знесено вітром за межі поля (ризик для сусідніх культур, пасік, водойм). Фактична ефективність обробки — лише 35%.',
    );
    if (c) c.losses.drift = (c.losses.drift ?? 1) * 0.99;
  }

  // ---------------------------------------------------------------- температура
  if (!def.spreader && !frozen && def.mode !== 'fert') {
    const [tLo, tHi] = def.tOpt;
    if (tW < tLo - 3) {
      eff *= 0.45;
      notes.push(`холод +${fmt(tW, 0)} °C`);
      addMistake(
        s,
        `Обробка в холодну погоду: ${def.name} при +${fmt(tW, 0)} °C (робочий діапазон від +${tLo} °C)`,
        def.mode === 'systemic'
          ? 'Системні препарати діють лише тоді, коли рослина (бур\'ян) активно росте: д.р. поглинається листком і пересувається флоемою до точок росту. У холод фотосинтез і транспорт асимілятів майже зупинені — д.р. лишається на листку й розкладається.'
          : 'Шкідники в холод малорухливі й не живляться, тому майже не контактують з обробленою поверхнею.',
        `Ефективність ~${Math.round(eff * 100)}% — частина об'єктів виживе.`,
      );
    } else if (tW < tLo) {
      eff *= 0.8;
      notes.push(`прохолодно +${fmt(tW, 0)} °C`);
      addLog(s, 'warn', 'Прохолодно для обробки', `+${fmt(tW, 0)} °C — нижче оптимуму препарату (від +${tLo} °C): дія повільніша й слабша.`);
    } else if (tW > tHi) {
      notes.push(`спека +${fmt(tW, 0)} °C`);
      if (op === 'postHerbicide' || op === 'glyphosate' || op === 'retardant') {
        eff *= 0.7;
        addMistake(
          s,
          `Обробка в спеку: ${def.name} при +${fmt(tW, 0)} °C (оптимум до +${tHi} °C)`,
          'У спеку бур\'яни закривають продихи й потовщують кутикулу — препарат погано проникає. Культура в тепловому стресі гірше детоксикує д.р., тому селективність падає. Дрібні краплі випаровуються, не досягнувши листка.',
          c && c.emerged && op !== 'glyphosate' ? 'Ефективність ~70% і фітотоксичність для культури — втрата ~5% урожаю.' : 'Ефективність знижена приблизно на третину.',
        );
        if (c && c.emerged && op !== 'glyphosate') c.losses.phyto = (c.losses.phyto ?? 1) * 0.95;
      } else {
        eff *= op === 'insecticide' ? 0.65 : 0.8;
        addLog(s, 'warn', 'Обробка в спеку', `+${fmt(tW, 0)} °C: краплі випаровуються, продихи закриті${op === 'insecticide' ? '; піретроїди мають від\'ємний температурний коефіцієнт — у спеку діють слабше' : ''}. Краще працювати у вечірню зміну.`);
      }
    }
  }
  // азот по листю: сольовий опік
  if (op === 'nitrogen' && c && c.emerged && c.bbch >= 12 && !frozen) {
    const burn = (tW > 25 && dose > 30) || dose > 70;
    if (burn) {
      addMistake(
        s,
        `Опік листя азотом: ${fmt(dose, 0)} кг N/га${tW > 25 ? ` при +${fmt(tW, 0)} °C` : ''}`,
        'КАС-32 — концентрований сольовий розчин. На листку вода випаровується, концентрація солей зростає, і вони витягують воду з клітин (плазмоліз). Чим вища разова доза та температура, тим сильніший опік; тому КАС вносять струменевими розпилювачами, прохолодної пори, дробно.',
        'Некрози на листі, втрата частини асиміляційної поверхні — ~4% урожаю.',
      );
      c.losses.phyto = (c.losses.phyto ?? 1) * 0.96;
      c.leafFrost = Math.max(c.leafFrost, 0.12);
    }
  }

  // ---------------------------------------------------------------- фаза культури
  if (c && c.emerged) {
    const ripe = (pest && op !== 'desiccant' && op !== 'glyphosate' && c.bbch >= 83) || ((op === 'micro' || op === 'antistress') && c.bbch >= 80) || (op === 'nitrogen' && c.bbch >= 75 && CROPS[c.id].maturityBbch > 50);
    if (ripe) {
      notes.push(`дозрівання BBCH ${c.bbch}`);
      if (op !== 'nitrogen') eff *= 0.02;
      addMistake(
        s,
        `Обробка посіву у фазі дозрівання (${CROPS[c.id].name}, BBCH ${c.bbch}): ${def.name}`,
        op === 'nitrogen'
          ? 'Після наливу рослина вже не поглинає азот: коріння відмирає, листя жовтіє. Внесений азот лишається в ґрунті й восени вимивається або втрачається в атмосферу.'
          : 'Формування врожаю завершено: листя старіє й не поглинає речовини, хвороби та шкідники вже не впливають на масу зерна. Д.р. залишається на рослинах і потрапляє в продукцію.',
        op === 'nitrogen' ? 'Азот не використаний посівом, ризик забруднення ґрунтових вод нітратами.' : 'Жодного приросту врожаю; ризик залишків у продукції.',
      );
    }
    // строк очікування
    if (pest && def.phi > 0) {
      const dth = daysToHarvest(s, c);
      if (dth < def.phi) {
        c.residue = true;
        notes.push(`строк очікування ${def.phi} діб, до збирання ~${dth}`);
        addMistake(
          s,
          `Порушено строк очікування: ${def.name} (${def.phi} діб), до збирання ~${dth} діб`,
          'Строк очікування — мінімальний час між останньою обробкою та збиранням, за який д.р. розкладається до рівня нижче максимально допустимого (МДР). Він встановлений під час державної реєстрації препарату й обов\'язковий.',
          'Залишки д.р. у продукції перевищать МДР: партія не придатна для продовольчих цілей і експорту.',
        );
      }
    }
  }

  // ---------------------------------------------------------------- кратність та резистентність
  if (c && def.maxApps > 0) {
    const n = c.apps[op] ?? 0;
    if (n >= def.maxApps) {
      eff *= 0.6;
      notes.push(`${n + 1}-а обробка (дозволено ${def.maxApps})`);
      addMistake(
        s,
        `Перевищено кратність обробок: ${def.name} — ${n + 1}-а за сезон (дозволено ${def.maxApps})`,
        'Кратність обробок обмежена регламентом: сумарне навантаження д.р. на культуру й довкілля, накопичення залишків, а головне — відбір резистентних рас патогенів, популяцій шкідників і біотипів бур\'янів при повторній дії того самого механізму' + (def.moa ? ` (${def.moa})` : '') + '. Препарати потрібно чергувати.',
        'Ефективність помітно нижча (резистентність), підвищені залишки д.р. у продукції.',
      );
    } else if (n > 0 && def.moa) {
      eff *= 0.93 ** n;
    }
    c.apps[op] = n + 1;
  }

  // ---------------------------------------------------------------- економічний поріг шкідливості
  if (c && c.emerged && (op === 'insecticide' || op === 'acaricide')) {
    const kind = CROPS[c.id].pest.kind;
    const target = (op === 'insecticide' && kind === 'insect') || (op === 'acaricide' && kind === 'mite');
    const misuse = op === 'insecticide' && c.disease > 15 && c.pests < 5;
    if (target && !misuse && c.pests < PEST_EPSH[c.id] * 0.3 && c.bbch < 83) {
      notes.push('нижче ЕПШ');
      addMistake(
        s,
        `Обробка без досягнення ЕПШ: ${CROPS[c.id].pest.name} ${fmt(c.pests, 1)} ${CROPS[c.id].pest.unit} (ЕПШ ${PEST_EPSH[c.id]})`,
        'За чисельності нижче економічного порогу шкідливості втрати врожаю менші за шкоду від обробки. Інсектициди й акарициди знищують ентомофагів (сонечок, золотоочок, хижих кліщів), які стримують шкідника природно, і відбирають стійкі особини.',
        'Приросту врожаю немає; зростає ризик спалаху шкідника після загибелі ентомофагів.',
      );
    }
  }

  if (s.sprayMode === 'evening' && !def.spreader) notes.push('вечірня зміна');
  eff = round(clamp(eff, 0, 1.1), 3);
  return { eff, notes };
}
